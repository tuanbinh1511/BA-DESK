import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = (await readFile(new URL('../src/services/api.ts', import.meta.url), 'utf8')).replace('import.meta.env.VITE_API_BASE_URL', 'undefined');
const { outputText } = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } });
const api = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
let requests = 0;
globalThis.fetch = async () => { requests++; return Response.json({ ok: true }); };
await assert.rejects(api.api('/tasks', {}), /Chưa kết nối/);
assert.equal(requests, 0);
await api.api('/state');
assert.equal(api.getConnectionStatus(), 'connecting');
api.setConnectionStatus('connected');
api.setAccountRevision(4);
globalThis.fetch = async (_url, options) => {
  requests++;
  assert.equal(options.headers['X-Account-Revision'], '4');
  api.setAccountRevision(5);
  return Response.json({ ok: true });
};
await assert.rejects(api.api('/tasks', {}), /Tài khoản đã đổi/);
assert.equal(api.getConnectionStatus(), 'connected');
globalThis.fetch = async () => { requests++; throw new TypeError('offline'); };
const before = requests;
await assert.rejects(api.api('/tasks', {}), /Chưa xác nhận thao tác đã lưu/);
assert.equal(requests, before + 1, 'mutations must never auto-retry');
assert.equal(api.getConnectionStatus(), 'offline');
await assert.rejects(api.api('/tasks', {}), /Chưa kết nối/);
assert.equal(requests, before + 1);
api.setConnectionStatus('connected');
globalThis.fetch = async () => Response.json({ detail: 'Forbidden' }, { status: 403 });
await assert.rejects(api.api('/settings', {}, 'PUT'), /Forbidden/);
assert.equal(api.getConnectionStatus(), 'forbidden');
api.setConnectionStatus('connected');
globalThis.fetch = async () => new Response('<html>proxy error</html>');
await assert.rejects(api.api('/state'), /không hợp lệ/);
const originalTimer = globalThis.setTimeout;
globalThis.setTimeout = (fn) => originalTimer(fn, 1);
globalThis.fetch = async (_url, options) => new Promise((_resolve, reject) => {
  options.signal.addEventListener('abort', () => reject(new DOMException('aborted', 'AbortError')), { once: true });
});
await assert.rejects(api.api('/tasks', {}), /Chưa xác nhận thao tác đã lưu/);
assert.equal(api.getConnectionStatus(), 'offline');
globalThis.setTimeout = originalTimer;
console.log('Connection checks passed: offline guard, no auto-retry, account revision, forbidden, invalid JSON, timeout.');
